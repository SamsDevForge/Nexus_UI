import { expect, test } from "@playwright/test";

test("calendar demo supports manual scheduling and explains disconnected sources", async ({ page }, testInfo) => {
  if (process.env.CI) await page.context().addCookies([{ name: "nexus-focus-mode", value: "on", url: "http://127.0.0.1:3101" }]);
  const errors: string[] = [], calendarCalls: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("request", r => { if (r.url().includes("/api/v1/calendar")) calendarCalls.push(r.url()); });
  await page.goto("/app/calendar");
  await expect(page.getByText("No events in this view. Add a manual event or connect a source.", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Connect Google", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Connect Outlook", exact: true })).toBeDisabled();
  const date = await page.getByLabel("Week starting").inputValue();
  await page.getByRole("button", { name: "Add event", exact: true }).click();
  await page.getByLabel("Event title", { exact: true }).fill("Field visit");
  await page.getByLabel("Location", { exact: true }).fill("Test farm");
  await page.getByLabel("Starts", { exact: true }).fill(`${date}T10:00`);
  await page.getByLabel("Ends", { exact: true }).fill(`${date}T11:00`);
  await page.getByRole("button", { name: "Add sample event", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Field visit", exact: true })).toBeVisible();
  await expect(page.getByText("Sample event saved for this screen.", { exact: true })).toBeVisible();
  await page.getByLabel("Event title", { exact: true }).fill("Design review");
  await page.getByLabel("Starts", { exact: true }).fill(`${date}T11:05`);
  await page.getByLabel("Ends", { exact: true }).fill(`${date}T12:00`);
  await page.getByRole("button", { name: "Add sample event", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Make a little room", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Edit Field visit", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Edit Field visit", exact: true })).toBeFocused();
  await page.getByLabel("Event title", { exact: true }).fill("Updated visit");
  await page.getByRole("button", { name: "Save event changes", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Updated visit", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("heading", { name: "Room for what matters.", exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("calendar-agenda.png"), fullPage: true });
  await page.getByRole("heading", { name: "Your sources", exact: true }).scrollIntoViewIfNeeded();
  await page.getByText("Add a weekly timetable", { exact: true }).click();
  await expect(page.getByRole("button", { name: "Save timetable", exact: true })).toBeDisabled();
  await page.screenshot({ path: testInfo.outputPath("calendar-sources.png") });
  expect(calendarCalls).toEqual([]); expect(errors).toEqual([]);
  await page.reload();
  await expect(page.getByText("No events in this view. Add a manual event or connect a source.", { exact: true })).toBeVisible();
});
